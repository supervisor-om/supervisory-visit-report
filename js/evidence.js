    function norm(e, g) {
        const o = typeof e === 'string' ? { t: e } : Object.assign({}, e);
        o.s = o.s || (g && g.s) || 'lesson';
        o.group = g ? g.name : 'أدلّتك';
        o.top = !!(g && g.top);
        o.x = !!o.x;
        return o;
    }
    function itemOf(id) { return DATA[String(Number(id))] || null; }
    function groups(id, kind) {
        const it = itemOf(id), gone = removed[id] || {};
        if (!it) return [];
        const out = it.groups.map(g => ({ name: g.name, top: !!g.top, s: g.s || 'lesson',
            list: (g[kind] || []).map(e => norm(e, g)).filter(e => !gone[e.t]) })).filter(g => g.list.length);
        const mine = ((custom[id] || {})[kind] || []).filter(t => !gone[t]).map(t => norm({ t, mine: true }, null));
        if (mine.length) out.push({ name: 'أدلّتك', top: false, s: 'lesson', list: mine });
        return out;
    }
    function entries(id, kind) { return groups(id, kind).reduce((a, g) => a.concat(g.list), []); }
    function resolve(t, kind, score) {
        const q = (Q[kind] || Q.pos)[Number(score)] || 'أغلب';
        return String(t).replace(/\{كم\}/g, q);
    }
    function sample(list, n, rng) {
        const a = list.slice(), out = [];
        while (a.length && out.length < n) out.push(a.splice(Math.floor((rng || Math.random)() * a.length), 1)[0]);
        return out;
    }
    // الاختيار التلقائيّ: من أدلّة الحصة ما وُجدت، ولا حسّاس أبداً
    function pool(list) {
        const ok = list.filter(e => !e.x);
        const lesson = ok.filter(e => e.s === 'lesson');
        return lesson.length ? lesson : ok;
    }
    function pick(id, score, rng) {
        score = Number(score);
        const out = { pos: [], neg: [] };
        if (!itemOf(id) || !(score >= 1 && score <= 5)) return out;
        const P = pool(entries(id, 'pos')), N = pool(entries(id, 'neg'));
        let pos = [], neg = [];
        if (score === 1) {
            const tops = P.filter(e => e.top);
            if (tops.length) {
                pos = sample(tops, 1, rng);
                pos = pos.concat(sample(P.filter(e => e !== pos[0] && !e.top), 1, rng));
                if (pos.length < 2) pos = pos.concat(sample(P.filter(e => pos.indexOf(e) < 0), 1, rng));
            } else pos = sample(P, 2, rng);
        } else if (score === 2) pos = sample(P, 1, rng);
        else if (score === 3) { pos = sample(P, 1, rng); neg = sample(N, 1, rng); }
        else neg = sample(N, score === 5 ? 2 : 1, rng);
        out.pos = pos.map(e => resolve(e.t, 'pos', score));
        out.neg = neg.map(e => resolve(e.t, 'neg', score));
        return out;
    }
    // الوصف: جملة المستوى، ثمّ «ويتضح ذلك من خلال» الموجب (أو السالب في ٤–٥)، ثمّ في «ملائم» «، مع» ما ينقص
    function compose(level, sel, score) {
        score = Number(score);
        const L = String(level || '').replace(/\.\s*$/, '');
        const pos = (sel && sel.pos) || [], neg = (sel && sel.neg) || [];
        const join = l => l.join('، و');
        let main = score >= 4 ? neg : pos, tail = score === 3 ? neg : [];
        if (!main.length && tail.length) { main = tail; tail = []; }
        if (!main.length) return L ? L + '.' : '';
        let t = (L ? L + '، ' : '') + 'ويتضح ذلك من خلال ' + join(main);
        if (tail.length) t += '، مع ' + join(tail);
        return t + '.';
    }
    // جزء الوصف السالب: بعد «، مع» في «ملائم»، وبعد «من خلال» في ٤–٥
    function negPart(text, score) {
        const t = String(text || ''); score = Number(score);
        if (score === 3) { const i = t.lastIndexOf('، مع '); return i >= 0 ? t.slice(i + 5) : ''; }
        if (score >= 4) { const i = t.indexOf('من خلال '); return i >= 0 ? t.slice(i + 8) : ''; }
        return '';
    }
    // التوصية المرتبطة بأوّل دليلٍ سالبٍ مذكورٍ في الوصف
    function recFor(id, text, score) {
        const it = itemOf(id);
        if (!it) return null;
        const seg = negPart(text, score);
        if (!seg) return null;
        let best = null, at = Infinity;
        Object.keys(it.recs).forEach(key => {
            (it.recs[key].k || []).forEach(k => {
                const i = seg.indexOf(k);
                if (i >= 0 && i < at) { at = i; best = Object.assign({ key }, it.recs[key]); }
            });
        });
        return best;
    }
    function recText(rec) { return rec ? rec.r + '، ويقاس أثر ذلك في الزيارة القادمة من خلال ' + rec.m : ''; }
    // ترتيب البنود التي تُكتب لها توصيات: ٤–٥ أوّلاً (الأعلى درجةً ثمّ بالأولويّة)، ثمّ ٣ بالأولويّة — أربعٌ على الأكثر
    function orderRecs(scored, max) {
        const pr = id => { const i = PRIORITY.indexOf(Number(id)); return i < 0 ? 99 : i; };
        const weak = scored.filter(x => Number(x.score) >= 4).sort((a, b) => (b.score - a.score) || (pr(a.id) - pr(b.id)));
        const mid = scored.filter(x => Number(x.score) === 3).sort((a, b) => pr(a.id) - pr(b.id));
        return weak.concat(mid).slice(0, max || MAX_RECS).map(x => Number(x.id));
    }
    // ما تعرضه لوحة «تعديل الأدلة» للمستوى: أقسامٌ (ما تحقّق / ما ينقص) فيها المجموعات، وأدلّة الحصة من العين أوّلاً
    function panel(id, score, eye) {
        score = Number(score);
        const E = eye || {}, kinds = score >= 4 ? ['neg'] : score === 3 ? ['pos', 'neg'] : ['pos'];
        return kinds.map(kind => {
            const eyeList = (E[kind] || []).map(t => ({ raw: t, value: t, s: 'lesson', x: false, eye: true }));
            const seen = {}; eyeList.forEach(e => { seen[e.value] = 1; });
            const gs = groups(id, kind).map(g => ({ name: g.name, top: g.top,
                items: g.list.map(e => ({ raw: e.t, value: resolve(e.t, kind, score), s: e.s, x: e.x, mine: !!e.mine }))
                    .filter(e => !seen[e.value]) })).filter(g => g.items.length);
            if (eyeList.length) gs.unshift({ name: 'من الحصة', top: false, items: eyeList });
            return { kind, title: kind === 'neg' ? (score === 3 ? 'ما ينقص — يُكتب بعد «مع»' : 'ما رُصد') : (score === 3 ? 'ما تحقّق' : 'ما رُصد'), groups: gs };
        });
    }
    function addCustom(id, kind, t) {
        t = String(t || '').trim();
        if (!t) return false;
        const c = custom[id] = custom[id] || { pos: [], neg: [] };
        if (removed[id]) delete removed[id][t];
        if (entries(id, kind).some(e => e.t === t)) return false;
        c[kind].push(t);
        return true;
    }
    function remove(id, t) {
        const c = custom[id];
        if (c && (c.pos.indexOf(t) >= 0 || c.neg.indexOf(t) >= 0)) {
            c.pos = c.pos.filter(x => x !== t); c.neg = c.neg.filter(x => x !== t);
            return true;
        }
        (removed[id] = removed[id] || {})[t] = 1;
        return true;
    }
    function reset() { Object.keys(custom).forEach(k => delete custom[k]); Object.keys(removed).forEach(k => delete removed[k]); }

