        const s = st || {}, a = s.agree || {}, out = [];
        out.push('المداولة الإشرافيّة — ' + (clean(v.teacher) || '') + (clean(v.date) ? ' — ' + clean(v.date) : ''));
        out.push('الأسلوب: ' + plan.method.label + ' · النمط: ' + plan.style.label);
        if (plan.strengths.length) out.push('جوانب الإجادة: ' + plan.strengths.map(x => x.standard).join('، '));
        if (plan.focus.length) out.push('محور التطوير: ' + plan.focus.map(x => x.standard).join('، '));
